"""Approval-gated Notion video pipeline. Python 3.12 and Playwright."""
import argparse
import html
import json
import os
import sys
from pathlib import Path
import subprocess
import urllib.request

SOURCE = '3fe99be2-aa09-8098-b57d-000b14659f6e'
STAGES = {'待制作': 'script', '脚本已通过': 'storyboard', '分镜已通过': 'render'}


def request(url, token, body=None, method=None, notion=False, raw=False):
    headers = {'Authorization': f'Bearer {token}', 'Content-Type': 'application/json'}
    if notion:
        headers['Notion-Version'] = '2025-09-03'
    req = urllib.request.Request(url, data=json.dumps(body).encode() if body is not None else None,
                                 headers=headers, method=method)
    with urllib.request.urlopen(req, timeout=120) as response:
        data = response.read()
    return data if raw else json.loads(data)


def notion(path, body=None, method=None):
    return request('https://api.notion.com/v1/' + path, os.environ['NOTION_TOKEN'], body, method, True)


def text(prop):
    return ''.join(t.get('plain_text', t.get('text', {}).get('content', ''))
                   for t in prop.get(prop.get('type'), []))


def blocks(page):
    result, cursor = [], None
    while True:
        suffix = '?page_size=100' + (f'&start_cursor={cursor}' if cursor else '')
        data = notion(f'blocks/{page}/children' + suffix)
        result.extend(data['results'])
        if not data.get('has_more'):
            return result
        cursor = data['next_cursor']


def payload(page, kind):
    prefix = f'VIDEO_PIPELINE:{kind}:'
    found = []
    for block in blocks(page):
        if block['type'] == 'code':
            value = ''.join(x.get('plain_text', x.get('text', {}).get('content', ''))
                            for x in block['code']['rich_text'])
            if value.startswith(prefix):
                found.append(json.loads(value[len(prefix):]))
    if not found:
        raise RuntimeError(f'Missing {kind} generated by pipeline. Import the approved version first.')
    return found[-1]


def status(page, value):
    notion(f'pages/{page}', {'properties': {'制作状态': {'select': {'name': value}}}}, 'PATCH')


def save(page, kind, value, next_status):
    content = f'VIDEO_PIPELINE:{kind}:' + json.dumps(value, ensure_ascii=False)
    chunks = [content[i:i+1800] for i in range(0, len(content), 1800)]
    notion(f'blocks/{page}/children', {'children': [{
        'object': 'block', 'type': 'code', 'code': {'language': 'plain text',
        'rich_text': [{'type': 'text', 'text': {'content': x}} for x in chunks]}}]}, 'PATCH')
    status(page, next_status)


def ai(prompt):
    data = request('https://api.openai.com/v1/chat/completions', os.environ['OPENAI_API_KEY'], {
        'model': os.environ.get('TEXT_MODEL', 'gpt-4.1-mini'),
        'response_format': {'type': 'json_object'},
        'messages': [{'role': 'system', 'content': 'You create accurate English industrial educational videos. '
                      'Never invent company claims, specifications, numbers, or citations. Return JSON only.'},
                     {'role': 'user', 'content': prompt}]})
    return json.loads(data['choices'][0]['message']['content'])


def validate_board(board):
    slides = board.get('slides')
    if not isinstance(slides, list) or len(slides) != 10:
        raise ValueError('Exactly ten storyboard slides required')
    for slide in slides:
        for key in ['title', 'body', 'visual']:
            if not isinstance(slide.get(key), str) or not slide[key].strip():
                raise ValueError(f'Each slide needs {key}')
        if len(slide['title']) > 75 or len(slide['body']) > 180:
            raise ValueError('Slide text too long for template')
    return slides


def previews(board, output):
    slides = validate_board(board)
    output.mkdir(parents=True, exist_ok=True)
    paths = []
    for index, slide in enumerate(slides):
        title, body, visual = (html.escape(slide[k]) for k in ['title', 'body', 'visual'])
        # Deterministic, accurate typography rather than image-generated text.
        document = f'''<!doctype html><meta charset="utf-8"><title>Frame {index+1}</title>
<style>*{{box-sizing:border-box}}body{{margin:0;background:#efeee9;color:#23282b;font-family:Arial,sans-serif}}
main{{width:1920px;height:1080px;padding:100px 130px;position:relative;overflow:hidden}}
header{{font-size:24px;letter-spacing:5px;color:#596a73}}h1{{font-size:94px;max-width:1450px;margin:90px 0 40px;line-height:1.08}}
p{{font-size:42px;max-width:1350px;line-height:1.5}}.line{{height:7px;width:140px;background:#537b91}}
footer{{position:absolute;bottom:70px;font-size:23px;color:#596a73}}.number{{position:absolute;right:120px;bottom:60px;font-size:70px;color:#537b91}}</style>
<main><header>MOTOR SELECTION / TECHNICAL NOTES</header><h1>{title}</h1><div class="line"></div><p>{body}</p>
<footer>CONCEPT PREVIEW · {visual}</footer><div class="number">{index+1:02}</div></main>'''
        path = output / f'frame-{index+1:02}.html'
        path.write_text(document, encoding='utf-8')
        paths.append(path)
    links = ''.join(f'<li><a href="{p.name}">Frame {i+1}</a></li>' for i, p in enumerate(paths))
    (output/'index.html').write_text('<!doctype html><meta charset="utf-8"><h1>Storyboard preview</h1><ol>'+links+'</ol>', encoding='utf-8')
    return paths


def duration(path):
    return float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries',
        'format=duration', '-of', 'default=noprint_wrappers=1:nokey=1', str(path)]))


def run(command):
    subprocess.run([str(x) for x in command], check=True, stdout=subprocess.DEVNULL, timeout=180)


def screenshot_frames(paths):
    from playwright.sync_api import sync_playwright
    with sync_playwright() as playwright:
        executable = os.environ.get('CHROMIUM')
        if not executable and sys.platform.startswith('linux') and Path('/usr/bin/chromium').exists():
            executable = '/usr/bin/chromium'
        browser = playwright.chromium.launch(
            executable_path=executable,
            headless=True, args=['--disable-dev-shm-usage'])
        page = browser.new_page(viewport={'width':1920, 'height':1080})
        for path in paths:
            page.set_content(path.read_text(encoding='utf-8'), wait_until='load')
            page.screenshot(path=str(path.with_suffix('.png')))
        browser.close()


def concat_entry(path):
    """FFmpeg concat paths use forward slashes, including on Windows."""
    value = Path(path).resolve().as_posix()
    if '\n' in value or '\r' in value:
        raise ValueError('Media paths cannot contain newlines')
    return "file '" + value.replace("'", "'\\''") + "'\n"


def demo_video(board, output):
    """Local silent review draft; no external services or intro/outro."""
    paths = previews(board, output)
    screenshot_frames(paths)
    listing = output/'frames.txt'
    listing.write_text(''.join(concat_entry(p.with_suffix('.png')) + 'duration 4\n' for p in paths)
                       + concat_entry(paths[-1].with_suffix('.png')), encoding='utf-8')
    final = output/'body-preview.mp4'
    run(['ffmpeg','-y','-v','error','-f','concat','-safe','0','-i',listing,
         '-t','40','-vf','fps=30,format=yuv420p','-c:v','libx264','-preset','veryfast',
         '-movflags','+faststart',final])
    if abs(duration(final)-40) > .1:
        raise ValueError('Preview duration mismatch')
    return final


def render(board, script, output, intro, outro):
    body_only = intro is None and outro is None
    for path in ([] if body_only else [intro, outro]):
        if not path.is_file():
            raise ValueError(f'Missing provided video: {path}')
    body_seconds = 40 if body_only else 60 - duration(intro) - duration(outro)
    if not 30 <= body_seconds <= 45:
        raise ValueError(f'Body duration {body_seconds:.2f}s outside agreed 30–45s range')
    paths = previews(board, output)
    speech = request('https://api.openai.com/v1/audio/speech', os.environ['OPENAI_API_KEY'], {
        'model': os.environ.get('TTS_MODEL', 'gpt-4o-mini-tts'), 'voice': 'alloy',
        'input': script['narration'], 'response_format': 'wav'}, raw=True)
    audio = output/'narration.wav'
    audio.write_bytes(speech)
    if duration(audio) > body_seconds:
        raise ValueError('Narration exceeds body duration. Revise and reapprove script; no silent truncation.')
    screenshot_frames(paths)
    shot = body_seconds/len(paths)
    listing = output/'frames.txt'
    listing.write_text(''.join(concat_entry(p.with_suffix('.png')) + f'duration {shot:.9f}\n' for p in paths)
                       + concat_entry(paths[-1].with_suffix('.png')), encoding='utf-8')
    body = output/'body.mp4'
    run(['ffmpeg','-y','-v','error','-f','concat','-safe','0','-i',listing,'-i',audio,
         '-vf','fps=30,format=yuv420p','-af','apad','-t',body_seconds,
         '-c:v','libx264','-preset','veryfast','-c:a','aac',body])
    if body_only:
        if abs(duration(body)-40) > .3:
            raise ValueError('Body duration mismatch')
        return body
    normalized = []
    for i, path in enumerate([intro, body, outro]):
        dest = output/f'part-{i}.mp4'
        streams = json.loads(subprocess.check_output(['ffprobe','-v','error','-show_streams','-of','json',str(path)]))
        has_audio = any(s['codec_type']=='audio' for s in streams['streams'])
        cmd = ['ffmpeg','-y','-v','error','-i',path]
        if not has_audio:
            cmd += ['-f','lavfi','-i','anullsrc=r=48000:cl=stereo']
        cmd += ['-map','0:v:0','-map','0:a:0' if has_audio else '1:a:0',
                '-vf','scale=1920:1080:force_original_aspect_ratio=decrease,pad=1920:1080:(ow-iw)/2:(oh-ih)/2,fps=30,setsar=1',
                '-c:v','libx264','-preset','veryfast','-pix_fmt','yuv420p','-c:a','aac','-ar','48000','-ac','2',
                '-t',duration(path),dest]
        run(cmd)
        normalized.append(dest)
    concat = output/'parts.txt'
    concat.write_text(''.join(concat_entry(p) for p in normalized), encoding='utf-8')
    final = output/'final.mp4'
    run(['ffmpeg','-y','-v','error','-f','concat','-safe','0','-i',concat,'-c','copy','-movflags','+faststart',final])
    if abs(duration(final)-60) > .3:
        raise ValueError('Rendered duration is not 60 seconds')
    return final


def tick(args):
    filters = [{'property':'制作状态','select':{'equals':s}} for s in STAGES]
    query = {'filter': {'or': filters}, 'page_size':100}
    pages = []
    while True:
        data = notion(f'data_sources/{SOURCE}/query', query)
        pages.extend(data['results'])
        if not data.get('has_more'):
            break
        query['start_cursor'] = data['next_cursor']
    for page in pages:
        props = page['properties']
        stage = STAGES[props['制作状态']['select']['name']]
        # Never start an arbitrary topic: draft creation requires exact configured week.
        if stage == 'script' and (not args.week or text(props['Week']) != args.week):
            continue
        page_id = page['id']
        out = Path(args.output)/page_id
        out.mkdir(parents=True, exist_ok=True)
        if stage == 'script':
            result = ai('Create an approximately 40-second, 80–95 word narration for: '+text(props['Topic'])+
                        '. Return {"narration":"...", "claims_to_verify":["..."]}. '
                        'This is body only; intro and outro are supplied. Calm Nordic industrial minimalism.')
            if not isinstance(result.get('narration'), str) or not result['narration'].strip():
                raise ValueError('Empty narration')
            save(page_id, 'script', result, '待脚本审核')
        elif stage == 'storyboard':
            script = payload(page_id, 'script')
            result = ai('Create exactly 10 static editorial slides for this approved narration. '
                        'Return {"slides":[{"title":"short heading","body":"short on-screen text",'
                        '"visual":"concise visual direction"}]}. No invented specifications. '
                        'Use restrained Nordic industrial style. Narration: '+script['narration'])
            previews(result, out)
            save(page_id, 'storyboard', result, '待分镜审核')
        else:
            result = render(payload(page_id,'storyboard'), payload(page_id,'script'), out,
                            None if args.body_only else Path(os.environ.get('INTRO_FILE','assets/intro.mp4')),
                            None if args.body_only else Path(os.environ.get('OUTRO_FILE','assets/outro.mp4')))
            # Only signal review after a verified file exists. Delivery is a separate approved operation.
            save(page_id, 'render', {'file':str(result), 'delivery':'GitHub workflow artifact'}, '待视频审核')
        print(f'{page_id}: completed {stage}')
        # One task per invocation controls spend and prevents accidental batch production.
        return
    print('No eligible approved task. No AI requests made.')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--week', default=os.environ.get('VIDEO_WEEK',''))
    parser.add_argument('--output', default='output')
    parser.add_argument('--preview', help='Local storyboard JSON; no credentials needed')
    parser.add_argument('--demo', help='Render a silent 40-second body preview from storyboard JSON')
    parser.add_argument('--body-only', action='store_true', default=os.environ.get('BODY_ONLY') == 'true',
                        help='Render 40-second narrated body without intro/outro')
    args = parser.parse_args()
    if args.demo:
        print(demo_video(json.loads(Path(args.demo).read_text(encoding='utf-8')), Path(args.output)))
    elif args.preview:
        previews(json.loads(Path(args.preview).read_text(encoding='utf-8')), Path(args.output))
    else:
        missing = [name for name in ['NOTION_TOKEN', 'OPENAI_API_KEY'] if not os.environ.get(name)]
        if missing:
            parser.error('Missing secure credentials: ' + ', '.join(missing) +
                         '. A Notion page link does not grant API access. Use --demo for offline preview.')
        tick(args)


if __name__ == '__main__':
    main()
